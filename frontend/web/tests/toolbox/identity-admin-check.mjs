import { chromium, expect } from "@playwright/test";
import { readFile, writeFile } from "node:fs/promises";
import { resolve } from "node:path";

const root = resolve("../.."), base = "http://127.0.0.1:18990";
const password = (await readFile(resolve(root, ".env"), "utf8")).match(/^TB_ADMIN_PASSWORD=(.+)$/m)[1].trim();
const browser = await chromium.launch({ channel: "msedge", headless: true });
const context = await browser.newContext({ viewport: { width: 1440, height: 1000 } });
const page = await context.newPage(), errors = [], checks = [];
page.on("pageerror", error => errors.push(error.message));
const pass = text => { checks.push(text); console.log("PASS " + text); };
const suffix = Date.now().toString(36), username = "qa_ui_" + suffix;
let userId, roleId;
try {
  const login = await context.request.post(base + "/api/auth/login", { data: { username: "admin", password } });
  expect(login.ok()).toBeTruthy();
  const user = await context.request.post(base + "/api/admin/users", { data: { username, name: "管理页面验收", password: "Qa-" + suffix + "-Temporary!" } });
  expect(user.status()).toBe(201); userId = (await user.json()).id;
  await page.goto(base + "/#settings");
  await expect(page.getByRole("button", { name: "用户、角色与审计管理" })).toBeVisible();
  expect(page.url()).toContain("#/settings");
  await page.getByRole("button", { name: "用户、角色与审计管理" }).click();
  const dialog = page.getByRole("dialog", { name: "用户、角色与审计管理" });
  await expect(dialog).toBeVisible();
  await expect(dialog.getByText(username, { exact: true })).toBeVisible();
  pass("Legacy hash resolves through Vue Router; native user list renders");
  await page.getByRole("tab", { name: "角色与工具授权" }).click();
  const roleName = "验收角色" + suffix;
  await page.getByRole("textbox", { name: "新角色名称", exact: true }).fill(roleName);
  await page.getByRole("textbox", { name: "新角色编码", exact: true }).fill("qa_ui_" + suffix);
  const created = page.waitForResponse(r => r.url().endsWith("/system/role/create") && r.request().method() === "POST");
  await page.getByRole("button", { name: "创建角色", exact: true }).click();
  const response = await created; roleId = (await response.json()).data.id; expect([200, 201]).toContain(response.status());
  await page.locator(".system-permissions .el-checkbox").filter({ hasText: "JSON 格式化" }).click();
  await expect(page.getByRole("checkbox", { name: "JSON 格式化", exact: true })).toBeChecked();
  await page.getByRole("button", { name: "保存工具授权", exact: true }).click();
  await expect(page.getByRole("status")).toContainText("工具授权已保存");
  const detail = await (await context.request.get(base + `/api/v1/system/role/detail/${roleId}`)).json();
  expect(detail.data.menus.map(m => m.permission)).toEqual(["toolbox:tool:json.format"]);
  pass("Create role and save real tool permissions through native FastapiAdmin APIs");
  await page.getByRole("tab", { name: "用户管理", exact: true }).click();
  const row = page.locator(".el-table__row").filter({ hasText: username });
  await row.locator(".el-select").click();
  await page.getByRole("option", { name: roleName, exact: true }).click();
  await page.getByRole("option", { name: "工具箱成员", exact: true }).click();
  await page.keyboard.press("Escape");
  await row.getByRole("button", { name: "保存", exact: true }).click();
  await expect(page.getByRole("status")).toContainText("账号已更新");
  const saved = await (await context.request.get(base + `/api/v1/system/user/detail/${userId}`)).json();
  expect(saved.data.role_ids).toEqual([roleId]);
  pass("User role assignment is persisted");
  await page.getByRole("tab", { name: "操作审计", exact: true }).click();
  await page.getByRole("button", { name: "刷新记录", exact: true }).click();
  await expect(dialog.locator(".el-table:visible .el-table__row").first()).toBeVisible();
  await page.screenshot({ path: resolve(root, "artifacts/identity-admin-dark.png"), fullPage: true });
  pass("Native audit table renders inside the existing workbench");
  await page.setViewportSize({ width: 390, height: 844 });
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  expect(errors).toEqual([]);
  pass("Mobile dialog has no page overflow or JavaScript errors");
  await writeFile(resolve(root, "artifacts/identity-admin-check.json"), JSON.stringify({ checks, errors }, null, 2));
} finally {
  if (userId) await context.request.delete(base + "/api/v1/system/user/delete", { data: [userId] });
  if (roleId) await context.request.delete(base + "/api/v1/system/role/delete", { data: [roleId] });
  await context.request.post(base + "/api/auth/logout");
  await browser.close();
}
